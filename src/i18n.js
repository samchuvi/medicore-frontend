// ─── SUPPORTED LANGUAGES ─────────────────────────────────────────────────────
// The system detects the user's device / browser language and shows the UI in
// English, French or Arabic. Anything else falls back to English.
export const LANGUAGES = [
  { code: "en", label: "English", nativeLabel: "English", dir: "ltr" },
  { code: "fr", label: "French", nativeLabel: "Français", dir: "ltr" },
  { code: "ar", label: "Arabic", nativeLabel: "العربية", dir: "rtl" },
];

const RTL_LANGUAGES = ["ar"];

export function isRtl(lng) {
  return RTL_LANGUAGES.includes((lng || "en").split("-")[0]);
}

// Keep <html dir/lang> in sync with the active language so Arabic renders
// right-to-left automatically.
function applyDirection(lng) {
  const base = (lng || "en").split("-")[0];
  const dir = isRtl(base) ? "rtl" : "ltr";
  if (typeof document !== "undefined") {
    document.documentElement.setAttribute("dir", dir);
    document.documentElement.setAttribute("lang", base);
  }
}

